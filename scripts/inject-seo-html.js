function escapeHtml(str) {
    return String(str)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;");
}

function buildBody(page) {
    const paras = page.paragraphs.map((p) => `<p>${escapeHtml(p)}</p>`).join("\n");
    return `<main id="seo-static" style="max-width:48rem;margin:0 auto;padding:2rem 1.25rem;font-family:Cairo,sans-serif;line-height:1.8;color:#111">
<h1>${escapeHtml(page.h1)}</h1>
${paras}
</main>`;
}

function applyMeta(html, page) {
    const canonical = `${SITE_URL}${page.path === "/" ? "" : page.path}`;
    let out = html;

    out = out.replace(/<title>[^<]*<\/title>/i, `<title>${escapeHtml(page.title)}</title>`);

    if (/<meta\s+name="description"/i.test(out)) {
        out = out.replace(
            /<meta\s+name="description"\s+content="[^"]*"\s*\/?>/i,
            `<meta name="description" content="${escapeHtml(page.description)}">`
        );
    } else {
        out = out.replace("</head>", `  <meta name="description" content="${escapeHtml(page.description)}">\n</head>`);
    }

    const headExtras = [
        `<link rel="canonical" href="${canonical}">`,
        `<meta property="og:title" content="${escapeHtml(page.title)}">`,
        `<meta property="og:description" content="${escapeHtml(page.description)}">`,
        `<meta property="og:url" content="${canonical}">`,
        `<meta property="og:type" content="website">`,
        `<meta property="og:locale" content="ar_EG">`,
        `<meta property="og:site_name" content="الهواري صن">`,
    ].join("\n  ");

    // Replace first og:title / og:description / og:url if present; otherwise append before </head>
    out = out.replace(/<meta\s+property="og:title"\s+content="[^"]*"\s*\/?>/i, "");
    out = out.replace(/<meta\s+property="og:description"\s+content="[^"]*"\s*\/?>/i, "");
    out = out.replace(/<meta\s+property="og:url"\s+content="[^"]*"\s*\/?>/i, "");
    out = out.replace(/<meta\s+property="og:type"\s+content="[^"]*"\s*\/?>/i, "");
    out = out.replace(/<link\s+rel="canonical"\s+href="[^"]*"\s*\/?>/i, "");
    out = out.replace("</head>", `  ${headExtras}\n</head>`);
    out = out.replace('<div id="root"></div>', `<div id="root">${buildBody(page)}</div>`);

    return out;
}

function main() {
    // Always start from Vite's empty shell (or strip a previous SEO inject).
    let template = readFileSync(join(DIST, "index.html"), "utf8");
    template = template.replace(/<div id="root">[\s\S]*?<\/div>(?=\s*<\/body>)/i, '<div id="root"></div>');

    if (!/<div id="root"><\/div>/i.test(template)) {
        throw new Error('Expected <div id="root"></div> in built index.html');
    }

    for (const page of PAGES) {
        const html = applyMeta(template, page);
        if (page.path === "/") {
            writeFileSync(join(DIST, "index.html"), html, "utf8");
        } else {
            const dir = join(DIST, page.path.slice(1));
            mkdirSync(dir, { recursive: true });
            writeFileSync(join(dir, "index.html"), html, "utf8");
        }
        console.log("SEO HTML:", page.path);
    }
}

main();
